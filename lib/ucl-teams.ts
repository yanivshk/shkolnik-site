/** בלי גרשיים, נקודות וגרש: "פ.ס.ז'" → "פסז", "מצ'סטר" → "מצסטר" */
const norm = (s: string) => s.replace(/["'׳״.]/g, "").replace(/\s+/g, " ").trim();

export function uclLogo(name: string): string | undefined {
  const n = norm(name);
  const hit = TEAMS.find(([re]) => re.test(n));
  return hit ? `/teams/ucl/${hit[1]}.png` : undefined;
}
